import { core } from "../core.js";
import { t } from "../i18n-utils.js";
import { apiUrl, appRequestHeaders, hasRemote } from "../remote.js";
import { isFeatureGatingEnabled } from "../app-features.js";
import { toastHelper } from "../viewer-utils.js";

// The worker's optional AI assistance (worker/ai.py): which features it
// offers this viewer (GET /api/ai/config) and the requests to them. Off
// unless the worker has WORKER_AI_ENABLED and an API key; viewer-settings
// viewer.ai: false hides it even then. Every answer is a suggestion shown
// next to the data it came from, marked as made by AI.

let configRequest = null;

export function isAIAllowedByViewer() {
  const setting = core.CONFIG?.viewer?.ai;
  if (setting === false) return false;
  if (setting && typeof setting === "object" && setting.enabled === false) return false;
  return true;
}

// {enabled, features, model} - fetched once per session; a worker without
// the endpoint (Drupal, older workers, static hosting) means "off".
export function fetchAIConfig({ refresh = false } = {}) {
  if (!isAIAllowedByViewer() || !hasRemote()) return Promise.resolve({ enabled: false, features: [] });
  if (refresh) configRequest = null;
  if (!configRequest) {
    configRequest = fetch(apiUrl("/api/ai/config"), { cache: "no-store", headers: appRequestHeaders() })
      .then((response) => (response.ok ? response.json() : null))
      .then((config) => (config && typeof config === "object" ? config : { enabled: false, features: [] }))
      .catch(() => ({ enabled: false, features: [] }));
  }
  return configRequest;
}

export async function hasAIFeature(feature) {
  return aiFeatureState(await fetchAIConfig(), feature) === "on";
}

// "on": offered to this user; "locked": the worker has it, but not for this
// user's plan (WORKER_AI_ACCESS) - in the app, where plans are sold, the
// tool is shown with a lock and opens the plans panel; "off": hidden.
export function aiFeatureState(config, feature) {
  const offered = Array.isArray(config?.features) && config.features.includes(feature);
  if (config?.enabled && offered) return "on";
  if (config?.restricted && offered && isFeatureGatingEnabled()) return "locked";
  return "off";
}

export async function aiAvailability(feature) {
  return aiFeatureState(await fetchAIConfig(), feature);
}

// A locked AI tool was used: the app's plans panel, at Business.
export function showAILocked(viewer) {
  toastHelper("planLocked", "info", { key: "plan-locked", replace: true });
  viewer.showLockedFeature?.("aiAssistant");
}

export class AIRequestError extends Error {
  constructor(message, status = 0, code = "") {
    super(message);
    this.status = status;
    this.code = code;
  }
}

// POST to an /api/ai/ endpoint; resolves to the answer, rejects with an
// AIRequestError carrying a message fit to show.
export async function aiRequest(path, body = {}) {
  let response;
  try {
    response = await fetch(apiUrl(path), {
      method: "POST",
      cache: "no-store",
      headers: { ...appRequestHeaders(), "Content-Type": "application/json" },
      body: JSON.stringify({ lang: core.currentLanguage || "en", ...body }),
    });
  } catch {
    throw new AIRequestError(t("ai.offline", "The AI assistant could not be reached."));
  }
  let data = null;
  try {
    data = await response.json();
  } catch {
    data = null;
  }
  if (!response.ok) {
    // Without JSON the answer came from a proxy in front of the worker:
    // 524 is Cloudflare giving up after 100 s.
    const message = response.status === 429
      ? t("ai.rateLimited", "AI request limit reached. Try again later.")
      : data?.error || (response.status === 524
        ? t("ai.timeout", "The AI answer took too long. Try again or ask a narrower question.")
        : `${t("ai.failed", "The AI assistant could not answer.")} (HTTP ${response.status})`);
    throw new AIRequestError(message, response.status, data?.code || "");
  }
  return data || {};
}

// The line under every AI answer.
export function aiDisclaimer(model) {
  const text = t("ai.disclaimer", "Generated by AI - check it before relying on it.");
  return model ? `${text} (${model})` : text;
}
